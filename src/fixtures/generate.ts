// Rulebook-driven issuer fixture generation (FR-013, issue #44).
//
// The generator loads one pinned rulebook version, matches the caller-supplied
// schema documents to its attestation references, verifies their sha256 SRI
// values and prepares them in-process (cheap bounds only). The expensive work -
// compiling the untrusted schemas, synthesizing the payload, applying overrides
// and deriving verified negative cases - runs in the shared resource-bounded
// sandbox child, so a hostile pinned schema cannot block the HTTP event loop.
//
// Fixtures are unsigned claim payloads. They are not SD-JWT VCs, are not
// signed, and are not issued credentials; signing and issuance stay with the
// external issuer implementation.

import { fileURLToPath } from 'node:url'

import { sha256Hex } from '../registry/digest'
import { invalidInput, notFound } from '../registry/errors'
import type { RulebookVersion } from '../registry/types'
import { parseRulebookVersionDocument } from '../registry/versioning'
import { prepareSchemaDocuments } from '../validation/schema'
import {
  DEFAULT_SANDBOX_LIMITS,
  runSandboxChild,
  type SandboxFailure,
  type SchemaSandboxLimits,
} from '../validation/schema-sandbox'
import type { SnapshotSchemaReference } from '../validation/types'

import { parseGenerateIssuerFixtureInput } from './request'
import {
  FIXTURE_SANDBOX_REASONS,
  parseFixtureSandboxResult,
  type FixtureSandboxRequest,
  type FixtureSandboxResult,
} from './sandbox'
import {
  ISSUER_FIXTURE_KIND,
  type IssuerFixtureAttestationEvidence,
  type IssuerFixtureDiagnostic,
  type IssuerFixtureResult,
  type IssuerFixtureRulebookEvidence,
  type IssuerFixtureSchemaReferenceEvidence,
  type IssuerFixtureService,
  type IssuerFixtureSource,
} from './types'

/** Boundaries every generated fixture carries. */
const FIXTURE_LIMITATIONS: readonly string[] = [
  'A fixture is an unsigned claim payload generated by AttestBook; it is not an issued credential, carries no signature and must never be presented as one.',
  'Attribute constraints come only from the exact schema documents supplied by the caller and matched to the pinned rulebook version; AttestBook does not fetch the referenced documents.',
  'Only a supported JSON Schema 2020-12 subset can be synthesized; SD-JWT VC Type Metadata references, unsupported keywords and unsatisfiable constraints are reported and never guessed.',
  'Payload validation checks the supplied schema documents only; cryptographic, trust, protocol and interoperability properties are not tested.',
  'Negative cases are derived from supported constraints and verified to fail the supplied documents; they are not an exhaustive conformance suite.',
  'No generated fixture, schema document or provider token is persisted; every response is computed from the pinned snapshot.',
]

/** Options for one fixture generator; tests inject deterministic sandbox limits. */
export interface IssuerFixtureGeneratorOptions {
  readonly source: IssuerFixtureSource
  readonly sandbox?: SchemaSandboxLimits
}

/**
 * The fixture sandbox could not run because it is busy or unavailable on this
 * platform. The HTTP layer maps this to `503 fixture_unavailable`; it is not a
 * client input error and no fixture was generated.
 */
export class IssuerFixtureUnavailableError extends Error {
  readonly code = 'fixture_unavailable' as const

  constructor(message: string) {
    super(message)
    this.name = 'IssuerFixtureUnavailableError'
  }
}

function defaultFixtureEntry(): string {
  const url = new URL(import.meta.url)
  return url.pathname.endsWith('.ts')
    ? fileURLToPath(new URL('./fixture-sandbox-entry.ts', url))
    : fileURLToPath(new URL('./fixtures/fixture-sandbox-entry.js', url))
}

function sandboxLimitMessage(kind: SandboxFailure, limits: SchemaSandboxLimits): string {
  const timeoutMs = limits.timeoutMs ?? DEFAULT_SANDBOX_LIMITS.timeoutMs
  const maxRssMb = Math.round((limits.maxRssBytes ?? DEFAULT_SANDBOX_LIMITS.maxRssBytes) / 2 ** 20)
  switch (kind) {
    case 'timeout':
      return `Fixture generation exceeded the ${timeoutMs} ms sandbox time limit; no fixture was generated.`
    case 'memory_exceeded':
      return `Fixture generation exceeded the ${maxRssMb} MiB sandbox memory limit; no fixture was generated.`
    case 'output_exceeded':
      return 'Fixture generation exceeded the sandbox output limit; no fixture was generated.'
    case 'busy':
      return 'The fixture generation sandbox is at its concurrency limit; no fixture was generated.'
    case 'unavailable':
      return 'The fixture generation sandbox is unavailable on this platform; no fixture was generated.'
    case 'failed':
      return 'The fixture generation sandbox failed; no fixture was generated.'
  }
}

async function runFixtureSandbox(
  request: FixtureSandboxRequest,
  limits: SchemaSandboxLimits,
): Promise<FixtureSandboxResult> {
  const outcome = await runSandboxChild(limits.entry ?? defaultFixtureEntry(), request, limits)
  if (outcome.kind !== 'ok') {
    const message = sandboxLimitMessage(outcome.kind, limits)
    if (outcome.kind === 'busy' || outcome.kind === 'unavailable') {
      throw new IssuerFixtureUnavailableError(message)
    }
    if (outcome.kind === 'failed') {
      throw new Error(message)
    }
    throw invalidInput(message)
  }
  const parsed = parseFixtureSandboxResult(outcome.raw)
  if (parsed === null) {
    throw new Error('the fixture generation sandbox returned malformed output')
  }
  return parsed
}

function rulebookEvidence(
  rulebookName: string,
  rulebookId: string,
  version: RulebookVersion,
  digest: string,
): IssuerFixtureRulebookEvidence {
  return {
    id: rulebookId,
    name: rulebookName,
    version: version.version,
    digest,
    digestVerified: true,
    specVersion: version.specVersion,
    status: version.status,
  }
}

function attestationEvidence(
  name: string,
  attestationLoS: string,
  bindingType: string,
  supportedFormats: readonly string[],
): IssuerFixtureAttestationEvidence {
  return { name, attestationLoS, bindingType, supportedFormats: [...supportedFormats] }
}

function referenceEvidence(
  reference: SnapshotSchemaReference,
  options: {
    readonly integrityVerified: boolean
    readonly kind: 'json_schema' | 'type_metadata' | null
    readonly applied: boolean
    readonly diagnostic?: string
  },
): IssuerFixtureSchemaReferenceEvidence {
  return {
    formatIdentifier: reference.formatIdentifier,
    uri: reference.uri,
    integrity: reference.integrity,
    integrityVerified: options.integrityVerified,
    kind: options.kind,
    applied: options.applied,
    ...(options.diagnostic === undefined ? {} : { diagnostic: options.diagnostic }),
  }
}

function isIntegrityUnverified(findingCode: string | undefined): boolean {
  return (
    findingCode === 'schema_document_unpinned' ||
    findingCode === 'invalid_integrity_value' ||
    findingCode === 'unsupported_integrity_algorithm' ||
    findingCode === 'schema_document_not_supplied'
  )
}

/** The typed, framework-independent issuer fixture generator. */
export class IssuerFixtureGenerator implements IssuerFixtureService {
  private readonly source: IssuerFixtureSource
  private readonly sandbox: SchemaSandboxLimits

  constructor(options: IssuerFixtureGeneratorOptions) {
    this.source = options.source
    this.sandbox = options.sandbox ?? {}
  }

  async generate(input: unknown): Promise<IssuerFixtureResult> {
    const request = parseGenerateIssuerFixtureInput(input)

    const rulebook = this.source.getRulebook(request.rulebookId)
    if (rulebook === null) {
      throw notFound('The rulebook does not exist.')
    }
    const version = this.source.getRulebookVersion(request.rulebookId, request.rulebookVersion)
    if (version === null) {
      throw notFound('The rulebook version does not exist.')
    }
    const content = this.source.getRulebookVersionContent(
      request.rulebookId,
      request.rulebookVersion,
    )
    if (content === null) {
      throw notFound('The rulebook version content does not exist.')
    }
    const digest = sha256Hex(content.bytes)
    if (digest !== version.contentDigest) {
      throw new Error('the stored rulebook version content does not match its recorded digest')
    }

    const document = parseRulebookVersionDocument(content.bytes)
    const attestation = document.attestations.find(
      (candidate) => candidate.name === request.attestationType,
    )
    if (attestation === undefined) {
      throw notFound('The attestation type does not exist in this rulebook version.')
    }

    if (request.format !== undefined && !attestation.supportedFormats.includes(request.format)) {
      throw invalidInput('format is not supported by the selected attestation type.')
    }

    const suppliedDocuments = request.schemaDocuments ?? []
    if (suppliedDocuments.length === 0) {
      throw invalidInput(
        'schemaDocuments must supply at least one schema document matching the selected attestation type.',
      )
    }
    for (const supplied of suppliedDocuments) {
      const matchesAttestation = attestation.schemaReferences.some(
        (reference) => reference.uri === supplied.uri,
      )
      if (!matchesAttestation) {
        throw invalidInput(
          'schemaDocuments contains a URI that the selected attestation type does not reference in this rulebook version.',
        )
      }
      if (
        request.format !== undefined &&
        !attestation.schemaReferences.some(
          (reference) =>
            reference.uri === supplied.uri && reference.formatIdentifier === request.format,
        )
      ) {
        throw invalidInput(
          'schemaDocuments contains a URI that the selected attestation type does not reference for the requested format in this rulebook version.',
        )
      }
    }

    const references =
      request.format === undefined
        ? attestation.schemaReferences
        : attestation.schemaReferences.filter(
            (reference) => reference.formatIdentifier === request.format,
          )
    if (references.length === 0) {
      throw invalidInput(
        'The selected attestation type has no schema reference for the requested format in this rulebook version.',
      )
    }

    // The shared preparation performs reference matching, sha256 SRI
    // verification, JSON parsing, depth and unsupported-keyword checks. Only
    // verified documents reach `pending`; everything else is reported.
    const prepared = prepareSchemaDocuments({
      references,
      documents: suppliedDocuments,
      claims: {},
    })

    const evidence: (IssuerFixtureSchemaReferenceEvidence | undefined)[] = Array.from(
      { length: references.length },
      () => undefined,
    )
    const diagnostics: IssuerFixtureDiagnostic[] = []
    const pendingJsonSchema: { index: number; pending: (typeof prepared.pending)[number] }[] = []

    for (const settled of prepared.settled) {
      const reference = references[settled.index]
      if (reference === undefined) {
        continue
      }
      const first = settled.application.findings[0]
      const code = first?.code
      if (
        code === 'integrity_mismatch' ||
        code === 'invalid_schema_document' ||
        code === 'schema_document_too_deep' ||
        code === 'invalid_json_schema'
      ) {
        throw invalidInput(
          first?.message ?? 'The supplied schema document cannot ground a fixture.',
        )
      }
      const diagnostic =
        first?.message ?? 'The schema reference did not contribute a usable document.'
      evidence[settled.index] = referenceEvidence(reference, {
        integrityVerified: !isIntegrityUnverified(code),
        kind: settled.application.kind,
        applied: false,
        diagnostic,
      })
      diagnostics.push({
        code: code ?? 'schema_reference_not_applied',
        message: diagnostic,
        path: `/schemaReferences/${settled.index}`,
      })
    }

    for (const pending of prepared.pending) {
      const reference = references[pending.index]
      if (reference === undefined) {
        continue
      }
      if (pending.kind === 'type_metadata') {
        const diagnostic =
          'SD-JWT VC Type Metadata declares claims and display values, not type constraints, so it cannot ground a generated payload.'
        evidence[pending.index] = referenceEvidence(reference, {
          integrityVerified: true,
          kind: 'type_metadata',
          applied: false,
          diagnostic,
        })
        diagnostics.push({
          code: 'type_metadata_not_synthesizable',
          message: diagnostic,
          path: `/schemaReferences/${pending.index}`,
        })
        continue
      }
      pendingJsonSchema.push({ index: pending.index, pending })
    }

    if (pendingJsonSchema.length === 0) {
      throw invalidInput(
        'No supplied schema document could ground a fixture: a matched JSON Schema 2020-12 document with a verified sha256 integrity value is required.',
      )
    }

    // Compiling the untrusted schemas, synthesizing the payload, applying
    // overrides and verifying every negative case all happen in the sandbox.
    const sandboxResult = await runFixtureSandbox(
      {
        items: pendingJsonSchema.map((entry) => entry.pending),
        overrides: request.overrides ?? [],
      },
      this.sandbox,
    )

    if (!sandboxResult.ok) {
      if (sandboxResult.reason === FIXTURE_SANDBOX_REASONS.noUsableDocuments) {
        throw invalidInput(
          'No supplied schema document could ground a fixture: a matched JSON Schema 2020-12 document with a verified sha256 integrity value is required.',
        )
      }
      if (sandboxResult.reason === FIXTURE_SANDBOX_REASONS.baselineValidationFailed) {
        throw invalidInput(
          'AttestBook could not synthesize a payload that satisfies every applied schema document; the supplied constraints are outside the supported synthesis subset.',
        )
      }
      if (sandboxResult.reason === FIXTURE_SANDBOX_REASONS.overridePathMissing) {
        throw invalidInput(
          `overrides[${sandboxResult.index ?? 0}].path does not exist in the generated fixture payload.`,
        )
      }
      throw invalidInput(sandboxResult.reason)
    }

    const appliedFormats = new Set<string>()
    for (const documentResult of sandboxResult.documents) {
      const reference = references[documentResult.index]
      if (reference === undefined) {
        continue
      }
      if (documentResult.applied) {
        appliedFormats.add(reference.formatIdentifier)
        evidence[documentResult.index] = referenceEvidence(reference, {
          integrityVerified: true,
          kind: 'json_schema',
          applied: true,
        })
        continue
      }
      const diagnostic =
        documentResult.diagnostic ?? 'The supplied JSON Schema document was not applied.'
      evidence[documentResult.index] = referenceEvidence(reference, {
        integrityVerified: true,
        kind: 'json_schema',
        applied: false,
        diagnostic,
      })
      diagnostics.push({
        code: 'schema_not_usable',
        message: diagnostic,
        path: `/schemaReferences/${documentResult.index}`,
      })
    }
    for (const entry of pendingJsonSchema) {
      if (evidence[entry.index] !== undefined) {
        continue
      }
      const reference = references[entry.index]
      if (reference === undefined) {
        continue
      }
      const diagnostic = 'The fixture sandbox did not report this schema document.'
      evidence[entry.index] = referenceEvidence(reference, {
        integrityVerified: true,
        kind: 'json_schema',
        applied: false,
        diagnostic,
      })
      diagnostics.push({
        code: 'schema_not_usable',
        message: diagnostic,
        path: `/schemaReferences/${entry.index}`,
      })
    }

    if (sandboxResult.negativeCases.length === 0) {
      diagnostics.push({
        code: 'no_negative_cases',
        message:
          'No supported constraint yielded a negative case that the supplied schema documents verify as failing.',
      })
    }

    const schemaReferences = evidence.filter(
      (entry): entry is IssuerFixtureSchemaReferenceEvidence => entry !== undefined,
    )
    const limitations = [...FIXTURE_LIMITATIONS]
    if (schemaReferences.some((reference) => !reference.integrityVerified)) {
      limitations.push(
        'One or more selected schema references had no verifiable sha256 integrity value; those documents did not ground the fixture.',
      )
    }
    if (schemaReferences.some((reference) => reference.kind === 'type_metadata')) {
      limitations.push(
        'One or more selected references are SD-JWT VC Type Metadata documents; their claim display information was not used to synthesize values.',
      )
    }

    return {
      kind: ISSUER_FIXTURE_KIND,
      signed: false,
      issued: false,
      rulebook: rulebookEvidence(rulebook.name, rulebook.id, version, digest),
      attestation: attestationEvidence(
        attestation.name,
        attestation.attestationLoS,
        attestation.bindingType,
        attestation.supportedFormats,
      ),
      formats: [...appliedFormats].sort(),
      schemaReferences,
      attributes: sandboxResult.attributes,
      payload: sandboxResult.payload,
      payloadValidation: sandboxResult.payloadValidation,
      overrides: sandboxResult.overrides,
      negativeCases: sandboxResult.negativeCases,
      diagnostics,
      limitations,
    }
  }
}
