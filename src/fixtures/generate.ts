// Rulebook-driven issuer fixture generation (FR-013, issue #44).
//
// The generator loads one pinned rulebook version and resolves its attestation
// schema references. A reference that is exactly the canonical AttestBook
// hosted-schema URL of this deployment is read from the immutable local store,
// never over HTTP, and its stored digest and rulebook SRI pin are verified; any
// other reference is matched to the caller-supplied documents and verified the
// same way. The verified documents are prepared in-process (cheap bounds only).
// The expensive work - compiling the untrusted schemas, synthesizing the
// payload, applying overrides and deriving verified negative cases - runs in the
// shared resource-bounded sandbox child, so a hostile pinned schema cannot block
// the HTTP event loop.
//
// Fixtures are unsigned claim payloads. They are not SD-JWT VCs, are not
// signed, and are not issued credentials; signing and issuance stay with the
// external issuer implementation.

