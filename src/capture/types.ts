// Public contracts for the normalized capture artifact envelope
// (FR-015/FR-018, issue #46).
//
// The envelope is an AttestBook-owned internal contract, not a TS11
// structure. It carries correlation and provenance metadata separately from a
// sensitive raw artifact: metadata is safe to index and log, while an inline
// artifact is returned in a distinct `sensitive` field and is never part of
// the normalised envelope. Credential bytes, claims, tokens and keys are
// therefore not embedded in every event and cannot leak into an index by
// construction.

/** Format marker carried by every normalized envelope. */
export const CAPTURE_ARTIFACT_KIND = 'attestbook.capture-artifact@1'

/** Version of the envelope contract this module accepts and produces. */
export const CAPTURE_ENVELOPE_VERSION = 1

/** Capture components AttestBook knows how to receive evidence from. */
export const CAPTURE_SOURCE_COMPONENTS = ['capture-issuer', 'capture-verifier'] as const
export type CaptureSourceComponent = (typeof CAPTURE_SOURCE_COMPONENTS)[number]

/** Interaction the captured evidence belongs to. */
export const CAPTURE_INTERACTION_TYPES = ['issuance', 'presentation', 'error'] as const
export type CaptureInteractionType = (typeof CAPTURE_INTERACTION_TYPES)[number]

/** Protocols an envelope version 1 artifact may describe. */
export const CAPTURE_PROTOCOLS = ['openid4vci', 'openid4vp'] as const
export type CaptureProtocol = (typeof CAPTURE_PROTOCOLS)[number]

/** Credential formats recognised by the pinned TS11 baseline. */
export const CAPTURE_CREDENTIAL_FORMATS = [
  'dc+sd-jwt',
  'mso_mdoc',
  'jwt_vc_json',
  'jwt_vc_json-ld',
  'ldp_vc',
] as const
export type CaptureCredentialFormat = (typeof CAPTURE_CREDENTIAL_FORMATS)[number]

/** Kinds of evidence a capture component may submit in envelope version 1. */
export const CAPTURE_ARTIFACT_TYPES = [
  'issuer-metadata',
  'credential-offer',
  'issued-credential',
  'presentation-request',
  'presentation-submission',
  'verification-outcome',
  'error-response',
] as const
export type CaptureArtifactType = (typeof CAPTURE_ARTIFACT_TYPES)[number]

/** Redaction state of the artifact the envelope describes. */
export const CAPTURE_REDACTION_STATUSES = ['none', 'partial', 'full'] as const
export type CaptureRedactionStatus = (typeof CAPTURE_REDACTION_STATUSES)[number]

/** Integrity algorithms envelope version 1 understands. */
export const CAPTURE_INTEGRITY_ALGORITHMS = ['sha256'] as const
export type CaptureIntegrityAlgorithm = (typeof CAPTURE_INTEGRITY_ALGORITHMS)[number]

/** Encodings accepted for an inline artifact. */
export const CAPTURE_ARTIFACT_ENCODINGS = ['utf8', 'base64'] as const
export type CaptureArtifactEncoding = (typeof CAPTURE_ARTIFACT_ENCODINGS)[number]

/** Scalar metadata value: an object or array is never accepted here. */
export type CaptureMetadataValue = string | number | boolean | null

/** Where a capture artifact came from and when it was captured. */
export interface CaptureProvenance {
  readonly sourceComponent: CaptureSourceComponent
  /** Exact component version reported by the source, when it reports one. */
  readonly sourceVersion: string | null
  /** Caller-supplied RFC 3339 capture timestamp, preserved verbatim. */
  readonly capturedAt: string
  /** `capturedAt` as Unix milliseconds, used for ordering. */
  readonly capturedAtMs: number
  /** RFC 3339 UTC timestamp of the normalization, generated by AttestBook. */
  readonly receivedAt: string
  readonly receivedAtMs: number
}

/** A secure reference to an artifact stored outside AttestBook. */
export interface CaptureArtifactReference {
  /** Absolute `https` URL without embedded credentials. */
  readonly uri: string
  readonly mediaType: string
  /** The source's declared artifact size in bytes, when it declares one. */
  readonly byteLength: number | null
}

/** Issuer or verifier associated with the captured interaction. */
export interface CaptureParty {
  readonly role: 'issuer' | 'verifier'
  /** Stable issuer identifier or verifier identifier, kept verbatim. */
  readonly identifier: string
  readonly name: string | null
}

/**
 * Integrity metadata over the *unredacted* raw artifact bytes. When an inline
 * artifact is supplied, the digest is recomputed and a mismatch is rejected;
 * for an external reference the declared digest cannot be verified here and
 * `verified` is `false`.
 */
export interface CaptureIntegrity {
  readonly algorithm: CaptureIntegrityAlgorithm
  /** Lowercase hexadecimal SHA-256 over the exact artifact bytes. */
  readonly digest: string
  readonly verified: boolean
}

/** Redaction applied to, or declared for, the referenced artifact. */
export interface CaptureRedaction {
  readonly status: CaptureRedactionStatus
  readonly policyRef: string | null
  /** JSON Pointers to redacted values, used by partial redaction. */
  readonly redactedPaths: readonly string[]
  /** SHA-256 of the redacted artifact bytes, when the source declares it. */
  readonly redactedDigest: string | null
}

/**
 * The normalized, metadata-only capture envelope. It is JSON-serializable and
 * deliberately contains no raw artifact bytes: an inline artifact is returned
 * separately as a `CaptureRawArtifact`.
 */
export interface CaptureArtifact {
  readonly kind: typeof CAPTURE_ARTIFACT_KIND
  readonly envelopeVersion: typeof CAPTURE_ENVELOPE_VERSION
  /** Stable, opaque capture identifier; correlation works across imports. */
  readonly captureId: string
  /** Opaque correlation identifier minted by the capture source or Credimi. */
  readonly correlationId: string
  readonly provenance: CaptureProvenance
  readonly interactionType: CaptureInteractionType
  readonly protocol: CaptureProtocol
  readonly credentialFormat: CaptureCredentialFormat
  readonly artifactType: CaptureArtifactType
  /** Exactly one of `artifactRef` and an inline artifact is present. */
  readonly artifactRef: CaptureArtifactReference | null
  readonly party: CaptureParty | null
  /** Associated Credimi test execution, kept opaque and verbatim. */
  readonly testExecutionRef: string | null
  readonly redaction: CaptureRedaction
  readonly integrity: CaptureIntegrity
  /** Extensible, non-sensitive scalar metadata. */
  readonly metadata: Readonly<Record<string, CaptureMetadataValue>>
}

/**
 * A raw inline artifact extracted from the submitted envelope. It is sensitive
 * data: callers must not log it, index it or merge it back into
 * `CaptureArtifact`.
 */
export interface CaptureRawArtifact {
  readonly mediaType: string
  readonly encoding: CaptureArtifactEncoding
  readonly byteLength: number
  /** Lowercase hexadecimal SHA-256 recomputed over the decoded bytes. */
  readonly digest: string
  /** The decoded artifact bytes. */
  readonly bytes: Uint8Array
}

/** An explicit, safe limitation of one normalization. */
export interface CaptureDiagnostic {
  readonly code: string
  readonly message: string
  readonly path?: string
}

/** The result of validating and normalizing one submitted envelope. */
export interface NormalizedCaptureArtifact {
  /** Metadata-only envelope, safe to index and log. */
  readonly envelope: CaptureArtifact
  /** Segregated raw artifact; `null` when the artifact stayed external. */
  readonly sensitive: CaptureRawArtifact | null
  readonly diagnostics: readonly CaptureDiagnostic[]
}

/** A redacted artifact produced by the default redaction policy. */
export interface RedactedCaptureArtifact {
  readonly envelope: CaptureArtifact
  /** Redacted raw bytes, or `null` when the artifact stayed external. */
  readonly sensitive: CaptureRawArtifact | null
  readonly diagnostics: readonly CaptureDiagnostic[]
}
